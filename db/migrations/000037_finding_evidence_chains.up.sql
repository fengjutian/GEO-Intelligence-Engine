CREATE TABLE finding_evidence_chains (
  finding_id BINARY(16) PRIMARY KEY,
  tenant_id BINARY(16) NOT NULL,
  project_id BINARY(16) NOT NULL,
  question_id BINARY(16) NOT NULL,
  response_id BINARY(16) NOT NULL,
  page_content_id BINARY(16) NOT NULL,
  task_id BINARY(16),
  retest_audit_id BINARY(16),
  change_summary TEXT NOT NULL,
  expected_outcome TEXT NOT NULL,
  verification_plan TEXT NOT NULL,
  retest_outcome VARCHAR(32) NOT NULL DEFAULT 'pending',
  created_by BINARY(16) NOT NULL,
  updated_by BINARY(16) NOT NULL,
  created_at DATETIME(6) NOT NULL,
  updated_at DATETIME(6) NOT NULL,
  KEY ix_finding_chain_project (tenant_id,project_id,updated_at),
  KEY ix_finding_chain_question (question_id),
  KEY ix_finding_chain_response (response_id),
  KEY ix_finding_chain_page (page_content_id),
  KEY ix_finding_chain_task (task_id),
  KEY ix_finding_chain_retest (retest_audit_id),
  CONSTRAINT fk_finding_chain_finding FOREIGN KEY (finding_id) REFERENCES findings(id),
  CONSTRAINT fk_finding_chain_project FOREIGN KEY (tenant_id,project_id) REFERENCES projects(tenant_id,id),
  CONSTRAINT fk_finding_chain_question FOREIGN KEY (question_id) REFERENCES questions(id),
  CONSTRAINT fk_finding_chain_response FOREIGN KEY (response_id) REFERENCES ai_responses(id),
  CONSTRAINT fk_finding_chain_page FOREIGN KEY (page_content_id) REFERENCES page_contents(id),
  CONSTRAINT fk_finding_chain_task FOREIGN KEY (task_id) REFERENCES optimization_tasks(id),
  CONSTRAINT fk_finding_chain_retest FOREIGN KEY (retest_audit_id) REFERENCES audits(id)
) ENGINE=InnoDB;
